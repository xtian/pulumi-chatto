// Generates provider/permissions_gen.go from the permission catalog of the Chatto
// client in the pinned Chatto source.
// Usage: bun tools/gen-permissions.ts > provider/permissions_gen.go

const source = process.env["CHATTO_SRC"];
if (!source) {
  throw new Error("CHATTO_SRC is not set. Run this script in `nix develop`.");
}

type Definition = { category: string; privileged?: boolean; scopes: readonly string[] };

const { PERMISSION_DEFINITIONS } = (await import(
  `${source}/packages/chatto-client/src/util/permissionCatalog.ts`
)) as { PERMISSION_DEFINITIONS: Record<string, Definition> };

const scopeKinds: Record<string, string> = {
  dm: "ScopeKindDM",
  group: "ScopeKindGroup",
  room: "ScopeKindRoom",
  server: "ScopeKindServer",
};

const scopeKind = (id: string, scope: string) => {
  const kind = scopeKinds[scope];
  if (!kind) {
    throw new Error(`Permission ${id} has unknown scope ${scope}`);
  }
  return kind;
};

// room.manage-members -> RoomManageMembers
const goName = (id: string) =>
  id
    .split(/[.-]/)
    .map((part) => `${part[0]!.toUpperCase()}${part.slice(1)}`)
    .join("");

const describe = ({ category, privileged, scopes }: Definition) => {
  const scopeText = `Scopes: ${scopes.join(", ")}.`;
  const privilegeText = privileged ? " A human session needs privileged mode to use it." : "";
  return `Category: ${category}. ${scopeText}${privilegeText}`;
};

const ids = Object.keys(PERMISSION_DEFINITIONS).sort();
const lines = [
  "// Code generated by tools/gen-permissions.ts from the Chatto client permission catalog. DO NOT EDIT.",
  "",
  "package provider",
  "",
  'import "github.com/pulumi/pulumi-go-provider/infer"',
  "",
  "// Permission identifiers that the supported Chatto version defines.",
  "const (",
  ...ids.map((id) => `\tPermission${goName(id)} Permission = ${JSON.stringify(id)}`),
  ")",
  "",
  "// Values lists the permissions for the schema.",
  "func (Permission) Values() []infer.EnumValue[Permission] {",
  "\treturn []infer.EnumValue[Permission]{",
  ...ids.map(
    (id) =>
      `\t\t{Name: ${JSON.stringify(goName(id))}, Value: Permission${goName(id)}, Description: ${JSON.stringify(describe(PERMISSION_DEFINITIONS[id]!))}},`,
  ),
  "\t}",
  "}",
  "",
  "// permissionScopes lists the scopes where each permission can be configured.",
  "var permissionScopes = map[Permission][]ScopeKind{",
  ...ids.map(
    (id) =>
      `\tPermission${goName(id)}: {${PERMISSION_DEFINITIONS[id]!.scopes.map((scope) => scopeKind(id, scope)).join(", ")}},`,
  ),
  "}",
  "",
];

process.stdout.write(lines.join("\n"));
